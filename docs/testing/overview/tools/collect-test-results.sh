#!/bin/bash
# =============================================================================
# collect-test-results.sh: run every host test suite and write the results
# as LaTeX macros, so the guide's numbers always match the latest real run.
#
# Runs INSIDE the pocat-tests container (it only needs bash, make, cmake, awk).
# Normally you don't call it by hand: build-docs.sh does it for you with
#
#   docker run --rm -v "<repo>:/app" -w /app --entrypoint bash pocat-tests \
#       docs/testing/overview/tools/collect-test-results.sh
#
# Inputs (environment, optional):
#   TR_COMMIT  short git hash of HEAD (the container has no git; the host passes it)
#   TR_DIRTY   "yes" if the working tree has uncommitted changes
#
# Outputs (in docs/testing/overview/generated/, ignored by git):
#   test-run.log      raw Unity output of every suite, in ctest order
#   build.log         output of the test build (look here if it fails)
#   test-results.tex  \TR... macros + table rows, \input by the guide
#
# How it works:
#   1. Builds the pocat_tests target in build_test/ (same as run_tests.sh).
#   2. Asks ctest for the suite list (ctest -N), so the order and the set of
#      suites always come from test/CMakeLists.txt.
#   3. Runs each suite binary directly. Unity prints one line per test:
#        <file>:<line>:<test_name>:PASS
#        <file>:<line>:<test_name>:FAIL: <message>
#        <file>:<line>:<test_name>:IGNORE: <message>
#      and awk counts those lines per suite.
#   4. A suite that exits non-zero without any FAIL line (ASan, deadlock,
#      timeout) is reported as "crashed", so the PDF never hides it.
#
# The script exits 0 when it managed to write the results, even if tests
# failed: a failing test is data for the document, not a build error.
# =============================================================================
set -u

REPO=/app
OUT_DIR="$REPO/docs/testing/overview/generated"
LOG="$OUT_DIR/test-run.log"
TEX="$OUT_DIR/test-results.tex"
TIMEOUT_S=60   # same per-suite limit as test/CMakeLists.txt

mkdir -p "$OUT_DIR"

# ---- 1. build (output kept in build.log) -----------------------------------
mkdir -p "$REPO/build_test" && cd "$REPO/build_test" && rm -f CMakeCache.txt
if ! { cmake -DBUILD_TESTING=ON .. && make -j"$(nproc)" pocat_tests; } > "$OUT_DIR/build.log" 2>&1; then
    echo "collect-test-results: test build FAILED, see $OUT_DIR/build.log" >&2
    exit 1
fi

# ---- 2. suite list, in ctest order -----------------------------------------
# ctest -N prints lines like "  Test  #3: test_task_management".
mapfile -t SUITES < <(ctest -N | awk '/Test +#[0-9]+:/ {print $NF}')
if [ "${#SUITES[@]}" -eq 0 ]; then
    echo "collect-test-results: ctest found no suites" >&2
    exit 1
fi

# ---- 3. run each suite, with marker lines around its output ----------------
: > "$LOG"
for s in "${SUITES[@]}"; do
    echo "===== SUITE $s" >> "$LOG"
    timeout "$TIMEOUT_S" "./test/$s" >> "$LOG" 2>&1
    echo "===== EXIT $s $?" >> "$LOG"
done

# ---- 4. log -> LaTeX --------------------------------------------------------
awk -v date="$(date -u '+%d/%m/%Y %H:%M UTC')" \
    -v commit="${TR_COMMIT:-unknown}" -v dirty="${TR_DIRTY:-no}" '
# Escape the characters LaTeX treats as special. Backslash first.
function tex(s) {
    gsub(/\\/, "\\textbackslash{}", s)
    gsub(/[{}_&%#$]/, "\\\\&", s)
    gsub(/\^/, "\\textasciicircum{}", s)
    gsub(/~/, "\\textasciitilde{}", s)
    return s
}
function short(s, n) { return (length(s) > n) ? substr(s, 1, n - 3) "..." : s }

/^===== SUITE / { cur = $3; order[++ns] = cur; next }
/^===== EXIT /  { code[$3] = $4; next }

# Unity result lines: 1=file 2=line 3=test 4=RESULT 5..=message
# (the message itself may contain ":", so it is glued back together).
{
    n = split($0, f, ":")
    if (n < 4) next
    res = f[4]
    if (res != "PASS" && res != "FAIL" && res != "IGNORE") next
    msg = ""
    for (i = 5; i <= n; i++) msg = msg (i > 5 ? ":" : "") f[i]
    sub(/^ +/, "", msg)
    total[cur]++
    if (res == "PASS")   pass[cur]++
    if (res == "FAIL")   { fail[cur]++; fl[++nf] = cur SUBSEP f[3] SUBSEP msg }
    if (res == "IGNORE") { ign[cur]++;  il[++ni] = cur SUBSEP f[3] SUBSEP msg }
}

END {
    T = P = F = I = green = crashed = 0
    for (k = 1; k <= ns; k++) {
        s = order[k]
        T += total[s]; P += pass[s]; F += fail[s]; I += ign[s]
        if (code[s] == 0) green++
        else if (fail[s] + 0 == 0) crashed++
    }
    print "% Generated by tools/collect-test-results.sh. Do not edit: rebuild with build-docs.sh."
    printf "\\def\\TRdate{%s}\n", date
    printf "\\def\\TRcommit{%s%s}\n", tex(commit), (dirty == "yes" ? " + uncommitted changes" : "")
    printf "\\def\\TRsuites{%d}\n", ns
    printf "\\def\\TRsuitesGreen{%d}\n", green
    printf "\\def\\TRsuitesCrashed{%d}\n", crashed
    printf "\\def\\TRtests{%d}\n", T
    printf "\\def\\TRpassed{%d}\n", P
    printf "\\def\\TRfailed{%d}\n", F
    printf "\\def\\TRignored{%d}\n", I

    # One row per suite: name & tests & passed & failed & ignored & status
    print "\\def\\TRsuiteRows{%"
    for (k = 1; k <= ns; k++) {
        s = order[k]
        st = (code[s] == 0) ? "green" : ((fail[s] + 0 > 0) ? "\\textbf{failing}" : "\\textbf{crashed}")
        printf "\\cd{%s} & %d & %d & %d & %d & %s\\\\\n", tex(s), total[s], pass[s], fail[s], ign[s], st
    }
    print "}"

    # Failing tests: suite & test & Unity message
    print "\\def\\TRfailRows{%"
    if (nf == 0) print "\\multicolumn{3}{@{}l}{\\emph{No failing tests.}}\\\\"
    for (k = 1; k <= nf; k++) {
        split(fl[k], x, SUBSEP)
        printf "\\cd{%s} & \\cd{%s} & %s\\\\\n", tex(x[1]), tex(x[2]), tex(short(x[3], 110))
    }
    print "}"

    # Ignored tests (KNOWN BUG): suite & test & reason without the prefix
    print "\\def\\TRignoreRows{%"
    if (ni == 0) print "\\multicolumn{3}{@{}l}{\\emph{No ignored tests.}}\\\\"
    for (k = 1; k <= ni; k++) {
        split(il[k], x, SUBSEP)
        m = x[3]; sub(/^KNOWN BUG /, "", m)
        printf "\\cd{%s} & \\cd{%s} & %s\\\\\n", tex(x[1]), tex(x[2]), tex(short(m, 110))
    }
    print "}"
}' "$LOG" > "$TEX"

echo "collect-test-results: wrote $TEX"
grep -E '^\\def\\TR(suites|suitesGreen|tests|failed|ignored)\{' "$TEX"
exit 0
